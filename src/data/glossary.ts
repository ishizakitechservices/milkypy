export const GLOSSARY_MAP: Record<string, GlossaryEntry> = GLOSSARY_TERMS.reduce(
  (acc, entry) => {
    acc[entry.id] = entry;
    // Also index by term lowercase
    acc[entry.term.toLowerCase()] = entry;
    return acc;
  },
  {} as Record<string, GlossaryEntry>
);

export function getGlossaryEntry(keyword: string): GlossaryEntry | undefined {
  const normalized = keyword.toLowerCase().trim();
  return GLOSSARY_MAP[normalized] || GLOSSARY_TERMS.find((t) => t.term.toLowerCase() === normalized);
}
